/**
 * 市町村ページ (/place/[pref]/[muni]) に出す「自治体ご担当者の方へ」導線の公開フラグ。
 *
 * ねらい: 自治体の担当者は「◯◯市 クマ」で検索して市町村ページに着地する。
 * 一方で法人向けの案内 (/for-gov) は、そこからたどり着く導線がなかった。
 * 担当者が最も気にするのは「うちの情報は合っているか」なので、営業文句ではなく
 * 「掲載内容の訂正を承ります」を入口にして /for-gov へ渡す。
 *
 * 住民・観光客には不要な情報なので、控えめな体裁で公式情報セクションの直後に置く。
 * 新しい URL は作らない (既存ページ内のブロックのみ) ので、インデックス面の影響はない。
 *
 * NEXT_PUBLIC_ なのでサーバ・クライアント双方から参照できる。
 * 未設定 / "true" 以外はすべて OFF (フェイルセーフ)。
 */
export function isGovCtaReleased(): boolean {
  return process.env.NEXT_PUBLIC_GOV_CTA === "true";
}
